"""Spoofing indicators. Each rule looks at one thing an analyst would check by hand."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import timedelta

from .auth import DKIMResult, DMARCResult, SPFResult
from .domains import FREE_MAIL, lookalike_of, org_domain
from .parser import ParsedEmail, domain_of

WEIGHTS = {"high": 30, "medium": 15, "low": 5, "info": 0}


@dataclass
class Finding:
    severity: str        # high / medium / low / info
    title: str
    detail: str


def _same_org(a: str, b: str) -> bool:
    return bool(a) and bool(b) and org_domain(a) == org_domain(b)


def check_identity(e: ParsedEmail, protected: list[str]) -> list[Finding]:
    out: list[Finding] = []

    # 1. Display name that contains a different email address: "PayPal <service@paypal.com>" <x@evil.com>
    embedded = re.findall(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+", e.from_name)
    for addr in embedded:
        if domain_of(addr) and not _same_org(domain_of(addr), e.from_domain):
            out.append(Finding("high", "Display name hides a different address",
                               f"The name shown is '{e.from_name}', but the real sender is {e.from_addr}."))
            break

    # 2. Display name claims a brand the sending domain doesn't belong to.
    if not embedded:
        for target in protected:
            label = org_domain(target).split(".")[0]
            if len(label) >= 3 and re.search(rf"\b{re.escape(label)}\b", e.from_name, re.IGNORECASE) \
                    and not _same_org(e.from_domain, target):
                out.append(Finding("medium", "Display name mentions a brand",
                                   f"The name '{e.from_name}' mentions '{label}', but the email comes from {e.from_domain}, "
                                   f"not {target}."))
                break

    # 3. Look-alike sending domain.
    target = lookalike_of(e.from_domain, protected)
    if target:
        out.append(Finding("high", "Look-alike sender domain",
                           f"{e.from_domain} imitates {target}."))
    if e.from_domain.startswith("xn--") or ".xn--" in e.from_domain:
        out.append(Finding("medium", "Internationalised (punycode) domain",
                           f"{e.from_domain} uses non-Latin characters, a common trick to imitate a real domain."))

    # 4. Reply-To sends answers somewhere else.
    for addr in e.reply_to:
        rdom = domain_of(addr)
        if rdom and not _same_org(rdom, e.from_domain):
            sev = "high" if rdom in FREE_MAIL and e.from_domain not in FREE_MAIL else "medium"
            out.append(Finding(sev, "Reply-To points to a different domain",
                               f"Replies go to {addr}, not to the sender at {e.from_domain}."))
            break

    # 5. Envelope sender (Return-Path) differs from the visible From.
    if e.return_path_domain and not _same_org(e.return_path_domain, e.from_domain):
        out.append(Finding("low", "Return-Path differs from From",
                           f"Bounces go to {e.return_path_domain} while the visible sender is {e.from_domain}. "
                           "This is normal for mailing services, but also common in spoofing."))

    # 6. Message-ID generated by an unrelated domain.
    mid_domain = e.message_id.strip("<>").rsplit("@", 1)[-1].lower() if "@" in e.message_id else ""
    if mid_domain and e.from_domain and not _same_org(mid_domain, e.from_domain) \
            and not _same_org(mid_domain, e.return_path_domain):
        out.append(Finding("low", "Message-ID from an unrelated domain",
                           f"The Message-ID was created by {mid_domain}."))
    return out


def check_route(e: ParsedEmail) -> list[Finding]:
    out: list[Finding] = []
    stamped = [h for h in e.hops if h.timestamp]
    for prev, cur in zip(stamped, stamped[1:]):
        if cur.timestamp < prev.timestamp - timedelta(minutes=5):
            out.append(Finding("medium", "Received timestamps go backwards",
                               f"A hop at {cur.by_host} is stamped before the previous hop. "
                               "Headers below the receiving server can be forged by the sender."))
            break
    for hop in e.hops:
        if hop.delay_seconds and hop.delay_seconds > 3600:
            out.append(Finding("low", "Long delay between hops",
                               f"{hop.delay_seconds / 3600:.1f} hours passed before {hop.by_host} received the message."))
            break
    if e.date and stamped and e.date > stamped[-1].timestamp + timedelta(minutes=10):
        out.append(Finding("low", "Date header is in the future",
                           "The Date header is later than the time the receiving server got the message."))
    if not e.sending_ip:
        out.append(Finding("info", "Sending IP not found",
                           "No public IP appears in the Received headers, so SPF could not be checked."))
    return out


def check_auth(spf: SPFResult, dkim: list[DKIMResult], dmarc: DMARCResult, receiver: dict) -> list[Finding]:
    out: list[Finding] = []
    if dmarc.result == "fail":
        sev = "high" if dmarc.policy in ("reject", "quarantine") else "medium"
        out.append(Finding(sev, "DMARC failed", dmarc.explanation))
    elif dmarc.result == "none":
        out.append(Finding("medium", "No DMARC policy", dmarc.explanation))

    if spf.result == "fail":
        out.append(Finding("medium", "SPF failed", f"{spf.ip} is not allowed to send mail for {spf.domain}."))
    elif spf.result == "softfail":
        out.append(Finding("low", "SPF soft-failed", f"{spf.domain} says {spf.ip} is probably not an authorised sender."))
    elif spf.result in ("permerror", "temperror"):
        out.append(Finding("low", f"SPF {spf.result}", spf.explanation))

    if any(d.result == "fail" for d in dkim):
        bad = next(d for d in dkim if d.result == "fail")
        out.append(Finding("medium", "DKIM signature failed",
                           f"Signature from {bad.domain or 'unknown'}: {bad.reason}. Old emails can also fail if the "
                           "sender has since rotated its keys."))
    elif all(d.result == "none" for d in dkim):
        out.append(Finding("low", "Not DKIM-signed", "The message carries no DKIM signature."))

    ours = {"spf": spf.result, "dmarc": dmarc.result,
            "dkim": "pass" if any(d.result == "pass" for d in dkim) else dkim[0].result}
    for method, verdict in receiver.items():
        if method in ours and verdict != ours[method] and ours[method] not in ("temperror",):
            out.append(Finding("info", f"Receiver's {method.upper()} verdict differs",
                               f"The receiving server recorded {method}={verdict}; this tool found {ours[method]}. "
                               "Differences are normal if DNS records changed since the email arrived."))
    return out


def score(findings: list[Finding]) -> tuple[int, str]:
    total = sum(WEIGHTS[f.severity] for f in findings)
    if total >= 45 or sum(f.severity == "high" for f in findings) >= 2:
        return total, "HIGH"
    if total >= 20:
        return total, "MEDIUM"
    return total, "LOW"
